import { writeFileSync } from 'node:fs';
import { ALL_SETTINGS, SECTIONS } from '../src/features';
import { ownerDefaults } from '../src/engine/profiles';
import { getPath } from '../src/ui/store';
import { BLOATWARE } from '../src/features/bloatware/catalog';

/** Regenerates docs/settings-mapping.md from the settings registry (single source of truth). */
const p = ownerDefaults();
const cell = (s: string) => s.replace(/\|/g, '\|').replace(/\n/g, ' ');
const fmt = (v: unknown) => {
  if (Array.isArray(v)) return v.length ? v.join(', ') : '(empty)';
  if (v && typeof v === 'object') return Object.entries(v).filter(([, x]) => x === true).map(([k]) => k).join(', ') || '(map)';
  return v === '' ? '(empty)' : String(v);
};
const out: string[] = [
  '# Settings mapping',
  '',
  '> Generated by `npm run docs:settings` from `src/features/*` — do not edit by hand.',
  '',
  'Each setting: owner default, Basic/Advanced placement, stage, exact XML/registry/policy mapping, applicability, caveat and mechanism status',
  '(`upstream-tested` = same mechanism the upstream generator uses; `documented` = Microsoft-documented setting/policy, not yet VM-verified here; `unverified` = needs VM confirmation).',
  'Validation rules live next to each setting in `src/features/<section>/index.ts` (`validate`).',
  '',
];
for (const sec of SECTIONS) {
  const defs = ALL_SETTINGS.filter((d) => d.section === sec.id);
  if (!defs.length) continue;
  out.push(`## ${sec.title}`, '', '| Setting | Path | Owner default | View | Stage | Mapping | Applies to | Caveat | Status |', '|---|---|---|---|---|---|---|---|---|');
  for (const d of defs) {
    const def = d.path === 'bloatware' ? 'see table below' : fmt(getPath(p, d.path));
    out.push(`| ${cell(d.label)} | \`${d.path}\` | ${cell(def)} | ${d.advanced ? 'Advanced' : 'Basic'} | ${d.stages.join(', ')} | ${cell(d.mapping)} | ${cell(d.applicability)} | ${cell(d.risk ?? '')} | ${d.verification ?? ''} |`);
  }
  out.push('');
  if (sec.id === 'bloatware') {
    out.push('### App catalog', '', '| App | Owner default | Removal steps (selector — applies to) | Note |', '|---|---|---|---|');
    for (const b of BLOATWARE) {
      const steps = b.steps.map((s) => `${s.kind}${s.selector ? `: \`${s.selector}\`` : (b.custom ? ` (${b.custom})` : '')} — ${s.appliesTo.join(', ')}`).join('<br>') || '(none: not removable)';
      out.push(`| ${b.label} | ${p.bloatware[b.id]} | ${steps} | ${cell(b.note ?? '')} |`);
    }
    out.push('');
  }
}
writeFileSync('docs/settings-mapping.md', out.join('\n'));
console.log(`Wrote docs/settings-mapping.md (${ALL_SETTINGS.length} settings)`);

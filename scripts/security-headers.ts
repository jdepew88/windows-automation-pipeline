import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';

/**
 * The website's security headers, defined once. Used by vite.config.ts (the Content-Security-Policy
 * <meta> written into the built pages) and checked against public/_headers (served by Cloudflare
 * Pages) by tests/unit/security-headers.test.ts. Regenerate the file with
 * `npm run headers` (scripts/write-headers.ts).
 *
 * Everything runs from the site's own files: no external scripts, styles, fonts, images or
 * requests. The only inline code is the Phase 9 health report preview (an iframe with `srcdoc`,
 * which inherits the page's policy): its one script and one style block are allowed by hash.
 */

const TEMPLATE = new URL('../src/engine/health/scripts/HealthReport.html', import.meta.url);

const hash = (s: string) => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`;

/** Hashes of the inline <script> and <style> blocks of the health report template (LF line ends, as rendered). */
export function inlineHashes(template = readFileSync(TEMPLATE, 'utf8')): { scripts: string[]; styles: string[] } {
  const t = template.replace(/\r\n/g, '\n');
  return {
    scripts: [...t.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => hash(m[1]!)),
    styles: [...t.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => hash(m[1]!)),
  };
}

export type CspMode = 'production' | 'development';

/**
 * Production: no inline styles except the hashed block, no WebSocket. Development (the Vite dev
 * server, i.e. the <meta> in the source HTML): Vite injects CSS as <style> elements and uses a
 * WebSocket for hot reload, so 'unsafe-inline' styles and ws: are added there only.
 * `frame-ancestors` is only honoured as a header, so it is added by the header, not the <meta>.
 */
export function contentSecurityPolicy(mode: CspMode = 'production', opts: { header?: boolean } = {}): string {
  const { scripts, styles } = inlineHashes();
  const directives: [string, string[]][] = [
    ['default-src', ["'self'"]],
    ['script-src', ["'self'", ...scripts]],
    ['style-src', ["'self'", ...(mode === 'development' ? ["'unsafe-inline'"] : styles)]],
    ['img-src', ["'self'"]],
    ['connect-src', ["'self'", ...(mode === 'development' ? ['ws:'] : [])]],
    ['object-src', ["'none'"]],
    ['base-uri', ["'none'"]],
    ['form-action', ["'none'"]],
    ...(opts.header ? ([['frame-ancestors', ["'none'"]]] as [string, string[]][]) : []),
  ];
  return directives.map(([k, v]) => `${k} ${v.join(' ')}`).join('; ');
}

/** Baseline headers for every response, and long caching for the content-hashed build assets. */
export function headersFile(): string {
  const all: [string, string][] = [
    ['Content-Security-Policy', contentSecurityPolicy('production', { header: true })],
    ['X-Content-Type-Options', 'nosniff'],
    ['X-Frame-Options', 'DENY'],
    ['Referrer-Policy', 'no-referrer'],
    ['Cross-Origin-Opener-Policy', 'same-origin'],
    ['Cross-Origin-Resource-Policy', 'same-origin'],
    ['Permissions-Policy', 'accelerometer=(), bluetooth=(), camera=(), display-capture=(), geolocation=(), gyroscope=(), hid=(), magnetometer=(), microphone=(), midi=(), payment=(), serial=(), usb=(), xr-spatial-tracking=()'],
    ['Strict-Transport-Security', 'max-age=31536000'],
  ];
  const lines = [
    '# Generated by scripts/security-headers.ts (npm run headers); do not edit by hand.',
    '# Cloudflare Pages applies these to every response; see docs/cloudflare-pages/deployment.md.',
    '/*',
    ...all.map(([k, v]) => `  ${k}: ${v}`),
    '',
    '# Content-hashed file names: a new build gets new names, so these never change.',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
  ];
  return lines.join('\n');
}
